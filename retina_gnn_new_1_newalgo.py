from torch.optim.lr_scheduler import OneCycleLR
from tqdm.notebook import tqdm
import torch.nn as nn
loss_fn = nn.PoissonNLLLoss(log_input=False)
EPOCHS = 2
MAX_LR = 2e-3
sched = OneCycleLR(opt, max_lr=MAX_LR, epochs=EPOCHS,
                   steps_per_epoch=len(train_ld), pct_start=0.25)

@torch.no_grad()
def evaluate(loader):
    model.eval(); P, Y = [], []
    for b in loader:
        b = b.to(DEVICE)
        P.append(model(b).cpu().view(-1, N_CELLS))
        Y.append(b['ganglion'].y.cpu().view(-1, N_CELLS))
    P, Y = torch.cat(P).numpy(), torch.cat(Y).numpy()
    cors = [np.corrcoef(P[:, c], Y[:, c])[0, 1] for c in range(N_CELLS)]
    return float(np.nanmean(cors)), np.array(cors)

best_corr, best_state = -1.0, None
for ep in range(1, EPOCHS + 1):
    model.train(); tot = 0.0
    for b in tqdm(train_ld, desc=f"epoch {ep}"):
        b = b.to(DEVICE)
        opt.zero_grad()
        out  = model(b)
        loss = loss_fn(out, b['ganglion'].y)          # <-- Poisson only, no Pearson term
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0)
        opt.step(); sched.step()
        tot += loss.item() * b.num_graphs
    vc, _  = evaluate(val_ld)
    tc, tp = evaluate(test_ld)
    flag = ""
    if vc > best_corr:
        best_corr = vc
        best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
        flag = "  <-- best"
    print(f"ep {ep:02d} | loss {tot/len(train_ds):.4f} | val {vc:.3f} | "
          f"TEST {tc:.3f} | per-cell {np.round(tp,3)}{flag}")

model.load_state_dict(best_state)
tc, tp = evaluate(test_ld)
print(f"\nFINAL TEST corr (Poisson-only) {tc:.3f} | per-cell {np.round(tp,3)}")
torch.save(model.state_dict(), MODEL_PATH_POISSON)   # separate file — your 0.655 checkpoint stays untouched

