def _pool_ts(P, arr, chunk=20000):
    outs = []
    for i in range(0, arr.shape[0], chunk):
        blk = arr[i:i+chunk].reshape(-1, GRID * GRID)
        outs.append((blk @ P.T).astype(np.float32))
