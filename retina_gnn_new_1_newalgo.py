class RetinaGraph(torch.utils.data.Dataset):
    def __init__(self, ts, rf, resp, frames):
        self.ts, self.rf, self.resp, self.frames = ts, rf, resp, frames
    def __len__(self):
        return len(self.frames)
    def __getitem__(self, i):
        t = int(self.frames[i]); s = t - WINDOW + 1
        d = HeteroData()
        for nt in _STIM_NODES:
            d[nt].x = torch.from_numpy(self.ts[nt][:, s:t+1].copy())
        for ntype, n in NODE_COUNTS.items():
            d[ntype].nid = torch.arange(n)
        for rel, ei in edge_index_dict.items():
            d[rel].edge_index  = ei
            d[rel].edge_weight = edge_weight_dict[rel]
        d['ganglion'].rf = torch.from_numpy(self.rf[:, s:t+1].copy())
        d['ganglion'].y  = torch.from_numpy(self.resp[:, t].copy())
        d['ganglion'].x  = torch.zeros((N_GANG, 1), dtype=torch.float32)
        return d

