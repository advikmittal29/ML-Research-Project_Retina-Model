def poisson_disc_sample(n_target, region=(0, 0, 1, 1), seed=0, k=30):
    rgen = np.random.default_rng(seed)
    xmin, ymin, xmax, ymax = region
    area = (xmax - xmin) * (ymax - ymin)

    def sample_with_radius(min_dist):
        cell_size = min_dist / np.sqrt(2)
        grid_w = int(np.ceil((xmax - xmin) / cell_size)) + 1
        grid_h = int(np.ceil((ymax - ymin) / cell_size)) + 1
        grid = -np.ones((grid_w, grid_h), dtype=int)
        points, active = [], []

        def grid_coords(p):
            return int((p[0]-xmin)/cell_size), int((p[1]-ymin)/cell_size)

        p0 = (rgen.uniform(xmin, xmax), rgen.uniform(ymin, ymax))
        points.append(p0); active.append(0)
        gx, gy = grid_coords(p0); grid[gx, gy] = 0

        while active:
            idx = active[rgen.integers(len(active))]
            base = points[idx]
            found = False
            for _ in range(k):
                ang = rgen.uniform(0, 2*np.pi)
                rad = rgen.uniform(min_dist, 2*min_dist)
                cand = (base[0] + rad*np.cos(ang), base[1] + rad*np.sin(ang))
                if not (xmin <= cand[0] < xmax and ymin <= cand[1] < ymax):
                    continue
                gx, gy = grid_coords(cand)
                ok = True
                for ix in range(max(0,gx-2), min(grid_w,gx+3)):
                    for iy in range(max(0,gy-2), min(grid_h,gy+3)):
                        j = grid[ix, iy]
                        if j != -1:
                            d = np.hypot(points[j][0]-cand[0], points[j][1]-cand[1])
                            if d < min_dist:
                                ok = False; break
                    if not ok: break
                if ok:
                    points.append(cand); active.append(len(points)-1)
                    grid[gx, gy] = len(points)-1
                    found = True
            if not found:
                active.remove(idx)
        return np.array(points, dtype=np.float32)

    lo, hi = 0.001, np.sqrt(area)
    best = None
    for _ in range(15):
        mid = (lo + hi) / 2
        pts = sample_with_radius(mid)
        if best is None or abs(len(pts) - n_target) < abs(len(best) - n_target):
            best = pts
        if len(pts) > n_target:
            lo = mid
        else:
            hi = mid

    if len(best) >= n_target:
        idx = rgen.choice(len(best), n_target, replace=False)
        return best[idx]
    else:
        pad_idx = rgen.choice(len(best), n_target - len(best), replace=True)
        pad = best[pad_idx] + rgen.normal(0, 0.01, (len(pad_idx), 2))
        return np.clip(np.vstack([best, pad]), [xmin, ymin], [xmax, ymax]).astype(np.float32)

